function fig = new_figure(cfg, heightCm)
%NEW_FIGURE  White, fixed-size figure with thesis fonts.
if nargin < 2, heightCm = cfg.fig.height; end
fig = figure('Color', 'w', 'Units', 'centimeters', 'Visible', 'off', ...
    'Position', [2 2 cfg.fig.width heightCm]);
try, theme(fig, 'light'); catch, end      % R2025a+ may default to dark theme
set(fig, 'DefaultAxesFontName', cfg.fig.font, 'DefaultAxesFontSize', cfg.fig.fontSize, ...
    'DefaultTextFontName', cfg.fig.font, 'DefaultLegendFontName', cfg.fig.font, ...
    'DefaultAxesBox', 'on', 'DefaultAxesTickDir', 'in', 'DefaultLineLineWidth', 1.1, ...
    'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', 'DefaultAxesGridAlpha', 0.15, ...
    'DefaultAxesMinorGridAlpha', 0.08, 'DefaultAxesLabelFontSizeMultiplier', 1, ...
    'DefaultAxesTitleFontSizeMultiplier', 1, 'DefaultAxesTitleFontWeight', 'normal');
end
