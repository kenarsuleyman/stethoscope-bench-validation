end

function a = args_predict(p, o)
a = {'--model', p.model};
if p.golden
    a{end+1} = '--golden-check';
else
    if isempty(p.wavDir), error('WAV klasörü seçilmeli (ya da Golden kontrol işaretlenmeli).'); end
    a = [a, {'--wav-dir', p.wavDir, '--out', [o '/probs.csv']}];
    if p.recursive, a{end+1} = '--recursive'; end
end
if p.appPath, a{end+1} = '--app-path'; end
end
