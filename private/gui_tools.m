% =====================================================================================================
function t = tool(key, cat, title, fn, help, params, varargin)
t = struct('key', key, 'cat', cat, 'title', title, 'fn', fn, 'help', help, 'kind', 'matlab', 'out', 'dir', ...
    'args', [], 'run', [], 'cmd', [], 'script', '', 'prepare', [], 'labelParam', '', 'copyLog', false, ...
    'stoppable', false);
t.params = [params{:}];
if isempty(params), t.params = par('', '', 'none', []); t.params(1) = []; end
for k = 1:2:numel(varargin), t.(varargin{k}) = varargin{k+1}; end
end

function T = add(T, t)
if isempty(T), T = t; else, T(end+1) = t; end
end

function p = par(name, label, type, default, varargin)
%PAR  Parameter: type text | num (scalar) | vec | choice | check | run | runs | multi | file | dir | toneresp
%   options: items {values, labels}, filter (run types: tones pcg sweep raw), optional, tip, ctx (gui_ctx key,
%   absolute path), pattern / startDir (file and dir pickers).
p = struct('name', name, 'label', label, 'type', type, 'default', {default}, 'items', {{}}, 'filter', {{}}, ...
    'optional', false, 'tip', '', 'ctx', '', 'pattern', '*.*', 'startDir', '');
for k = 1:2:numel(varargin), p.(varargin{k}) = varargin{k+1}; end
end

% ------------------------------------------------------------------ custom runners
function run_generate(p, o)
cfg = config();
if ~isempty(p.toneDbfs), cfg.stim.amp = 10^(p.toneDbfs/20); end
cfg.paths.stim = o;  cfg.paths.pcg = o;                  % pcg: <o>/stimulus/pcg_stimulus.wav + played_ref
switch p.stimType
    case 'pcg',   generate_pcg_stimulus(cfg);
    case 'sweep', generate_sweep(cfg);
    otherwise,    generate_test_signal(cfg);
end
end

function labels = measure_labels(p)
n = max(1, round(p.repeats));
if n == 1, labels = {p.label}; else, labels = arrayfun(@(k) sprintf('%s_run%d', p.label, k), 1:n, 'UniformOutput', false); end
end

function run_measure(p, o)
labels = measure_labels(p);
runs = cell(size(labels));
for k = 1:numel(labels)
    fprintf('\n=== Koşu %d / %d: %s ===\n', k, numel(labels), labels{k});
    runs{k} = run_measurement(labels{k}, p.mode, p.stimType, p.toneDbfs);
end
if p.combine && strcmp(p.stimType, 'tones') && numel(runs) >= 2
    fprintf('\n=== Birleşik figürler ===\n');
    make_figures(runs, fullfile(o, 'birlesik'));
end
end

function s = cmd_measure(p, o)
labels = measure_labels(p);
lv = '[]';  if ~isempty(p.toneDbfs), lv = num2str(p.toneDbfs); end
s = strjoin(cellfun(@(l) sprintf('run_measurement(''%s'', ''%s'', ''%s'', %s)', l, p.mode, p.stimType, lv), ...
    labels, 'UniformOutput', false), '; ');
if p.combine && strcmp(p.stimType, 'tones') && numel(labels) >= 2
    s = sprintf('%s; make_figures(<koşular>, ''%s'')', s, fullfile(o, 'birlesik'));
end
end

function run_analyze(p, o) %#ok<INUSD>
analyze_measurement(p.run);
if p.figs, make_figures(p.run); end
end

